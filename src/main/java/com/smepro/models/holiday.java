package com.smepro.models;

public class holiday {

	private int holiday_id;
	private int holiday_year;
	private String holiday_type;
	private String holiday_date;
	private String holiday_name;
	
	
	public int getHoliday_id() {
		return holiday_id;
	}
	public void setHoliday_id(int holiday_id) {
		this.holiday_id = holiday_id;
	}
	public int getHoliday_year() {
		return holiday_year;
	}
	public void setHoliday_year(int holiday_year) {
		this.holiday_year = holiday_year;
	}
	public String getHoliday_type() {
		return holiday_type;
	}
	public void setHoliday_type(String holiday_type) {
		this.holiday_type = holiday_type;
	}
	public String getHoliday_date() {
		return holiday_date;
	}
	public void setHoliday_date(String holiday_date) {
		this.holiday_date = holiday_date;
	}
	public String getHoliday_name() {
		return holiday_name;
	}
	public void setHoliday_name(String holiday_name) {
		this.holiday_name = holiday_name;
	}
	
	
	
	
}
