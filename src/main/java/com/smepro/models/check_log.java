package com.smepro.models;

public class check_log {
	
    private int id ;
    private String  checked_date;
    private String   checked_at;
    
    
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public String getChecked_date() {
		return checked_date;
	}
	public void setChecked_date(String checked_date) {
		this.checked_date = checked_date;
	}
	public String getChecked_at() {
		return checked_at;
	}
	public void setChecked_at(String checked_at) {
		this.checked_at = checked_at;
	}


}
