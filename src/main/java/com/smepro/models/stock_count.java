package com.smepro.models;

public class stock_count {

	
	private String batch;
	private String stock_code;
	private String stock_name;
	private Double total_system;
	private Double total_real;
	private String date_add;
	private String name_add;
	public String getBatch() {
		return batch;
	}
	public void setBatch(String batch) {
		this.batch = batch;
	}
	public String getStock_code() {
		return stock_code;
	}
	public void setStock_code(String stock_code) {
		this.stock_code = stock_code;
	}
	public String getStock_name() {
		return stock_name;
	}
	public void setStock_name(String stock_name) {
		this.stock_name = stock_name;
	}
	public Double getTotal_system() {
		return total_system;
	}
	public void setTotal_system(Double total_system) {
		this.total_system = total_system;
	}
	public Double getTotal_real() {
		return total_real;
	}
	public void setTotal_real(Double total_real) {
		this.total_real = total_real;
	}
	public String getDate_add() {
		return date_add;
	}
	public void setDate_add(String date_add) {
		this.date_add = date_add;
	}
	public String getName_add() {
		return name_add;
	}
	public void setName_add(String name_add) {
		this.name_add = name_add;
	}
	
	
	
}
