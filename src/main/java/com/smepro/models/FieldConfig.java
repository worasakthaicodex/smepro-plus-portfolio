package com.smepro.models;

public class FieldConfig {

	private int id;
	private int id_refer;
	private int process_id;
	private int allow_adding_items;
	private int data_access_interface;
	
	
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public int getId_refer() {
		return id_refer;
	}
	public void setId_refer(int id_refer) {
		this.id_refer = id_refer;
	}
	public int getProcess_id() {
		return process_id;
	}
	public void setProcess_id(int process_id) {
		this.process_id = process_id;
	}
	public int getAllow_adding_items() {
		return allow_adding_items;
	}
	public void setAllow_adding_items(int allow_adding_items) {
		this.allow_adding_items = allow_adding_items;
	}
	public int getData_access_interface() {
		return data_access_interface;
	}
	public void setData_access_interface(int data_access_interface) {
		this.data_access_interface = data_access_interface;
	}
	
	
	
	
}
