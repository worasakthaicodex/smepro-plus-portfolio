package com.smepro.models;

public class Management {
   
   private int id;
   private int process_id;
   private String management_title;
   private String management_abbreviation;
   private String user_access;
   private String admin_access;
   private int management_id;
   private int alert;
   
   
   
   
   
   
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public int getProcess_id() {
		return process_id;
	}
	public void setProcess_id(int process_id) {
		this.process_id = process_id;
	}
	public String getManagement_title() {
		return management_title;
	}
	public void setManagement_title(String management_title) {
		this.management_title = management_title;
	}
	public String getManagement_abbreviation() {
		return management_abbreviation;
	}
	public void setManagement_abbreviation(String management_abbreviation) {
		this.management_abbreviation = management_abbreviation;
	}
	public String getUser_access() {
		return user_access;
	}
	public void setUser_access(String user_access) {
		this.user_access = user_access;
	}
	public String getAdmin_access() {
		return admin_access;
	}
	public void setAdmin_access(String admin_access) {
		this.admin_access = admin_access;
	}
	public int getManagement_id() {
		return management_id;
	}
	public void setManagement_id(int management_id) {
		this.management_id = management_id;
	}
	public int getAlert() {
		return alert;
	}
	public void setAlert(int alert) {
		this.alert = alert;
	}
	   
	   
	
   
   
}
