package com.smepro.models;

public class Approve {
	
	
	private int flow;
	private String nextstpe;
	
	private String actiontype;
	private String approve_note;
	private String approve_date;
	
	
	
	
	public int getFlow() {
		return flow;
	}
	public void setFlow(int flow) {
		this.flow = flow;
	}
	public String getNextstpe() {
		return nextstpe;
	}
	public void setNextstpe(String nextstpe) {
		this.nextstpe = nextstpe;
	}
	public String getActiontype() {
		return actiontype;
	}
	public void setActiontype(String actiontype) {
		this.actiontype = actiontype;
	}
	public String getApprove_note() {
		return approve_note;
	}
	public void setApprove_note(String approve_note) {
		this.approve_note = approve_note;
	}
	public String getApprove_date() {
		return approve_date;
	}
	public void setApprove_date(String approve_date) {
		this.approve_date = approve_date;
	}
	
	
	
}
