package com.smepro.models;

public class Extension {

	
	private int extension_id;
	private String extension_name;
	private String extension_type;	
	private String extension_parameter;	
	private String extension_parameter_type;
	private int extension_process;
	private String component_req;
	private String extension_parameter_name;
	
	
	
	
	public int getExtension_id() {
		return extension_id;
	}
	public void setExtension_id(int extension_id) {
		this.extension_id = extension_id;
	}
	public String getExtension_name() {
		return extension_name;
	}
	public void setExtension_name(String extension_name) {
		this.extension_name = extension_name;
	}
	public String getExtension_type() {
		return extension_type;
	}
	public void setExtension_type(String extension_type) {
		this.extension_type = extension_type;
	}
	public String getExtension_parameter() {
		return extension_parameter;
	}
	public void setExtension_parameter(String extension_parameter) {
		this.extension_parameter = extension_parameter;
	}
	public String getExtension_parameter_type() {
		return extension_parameter_type;
	}
	public void setExtension_parameter_type(String extension_parameter_type) {
		this.extension_parameter_type = extension_parameter_type;
	}
	public int getExtension_process() {
		return extension_process;
	}
	public void setExtension_process(int extension_process) {
		this.extension_process = extension_process;
	}
	public String getComponent_req() {
		return component_req;
	}
	public void setComponent_req(String component_req) {
		this.component_req = component_req;
	}
	public String getExtension_parameter_name() {
		return extension_parameter_name;
	}
	public void setExtension_parameter_name(String extension_parameter_name) {
		this.extension_parameter_name = extension_parameter_name;
	}
	
	
	
}
