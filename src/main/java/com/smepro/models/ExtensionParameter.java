package com.smepro.models;

public class ExtensionParameter {
	
	private int id;
	private String extension_process;
	private String parameter_keyname;
	private String parameter_column;
	private String parameter_type;
	private String parameter_columnismain;
	private int use_extension_id;
	private int field_postion;
	
	
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public String getExtension_process() {
		return extension_process;
	}
	public void setExtension_process(String extension_process) {
		this.extension_process = extension_process;
	}
	public String getParameter_keyname() {
		return parameter_keyname;
	}
	public void setParameter_keyname(String parameter_keyname) {
		this.parameter_keyname = parameter_keyname;
	}
	public String getParameter_column() {
		return parameter_column;
	}
	public void setParameter_column(String parameter_column) {
		this.parameter_column = parameter_column;
	}
	public String getParameter_type() {
		return parameter_type;
	}
	public void setParameter_type(String parameter_type) {
		this.parameter_type = parameter_type;
	}
	public String getParameter_columnismain() {
		return parameter_columnismain;
	}
	public void setParameter_columnismain(String parameter_columnismain) {
		this.parameter_columnismain = parameter_columnismain;
	}
	public int getUse_extension_id() {
		return use_extension_id;
	}
	public void setUse_extension_id(int use_extension_id) {
		this.use_extension_id = use_extension_id;
	}
	public int getField_postion() {
		return field_postion;
	}
	public void setField_postion(int field_postion) {
		this.field_postion = field_postion;
	}
	
	
	
	
	
}
